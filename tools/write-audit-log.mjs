// Writes research/question-audit.md from the audit records in research/audit-records/.
//   node games/trivia/tools/write-audit-log.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const recDir = path.resolve(here, '../research/audit-records');
const orig = JSON.parse(fs.readFileSync(path.resolve(here, '../../../research/trivia-bank.json'), 'utf8')).questions;
const final = new Map(JSON.parse(fs.readFileSync(path.resolve(here, '../data/questions.json'), 'utf8')).questions.map((q) => [q.id, q]));
const read = (f) => JSON.parse(fs.readFileSync(path.join(recDir, f), 'utf8'));
const files = fs.readdirSync(recDir);
const first = new Map();
for (const f of files.filter((f) => /^batch-\d+\.result\.json$/.test(f)).sort()) for (const r of read(f)) first.set(r.id, { ...r, file: f });
const second = new Map();
for (const r of read('second-pass.json')) second.set(r.id, { ...r, set: r.suggested, file: 'second-pass.json (sample)' });
for (const f of files.filter((f) => /^verify-\d+\.result\.json$/.test(f)).sort()) for (const r of read(f)) second.set(r.id, { ...r, file: f });

const FLAGGED = ['hs-0017', 'hs-0188', 'hs-0299', 'hs-0393', 'hs-0480', 'hs-0072', 'hs-0090', 'hs-0107', 'hs-0133', 'hs-0464'];
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const short = (s, n = 70) => { s = cell(s); return s.length > n ? s.slice(0, n - 1) + '…' : s; };

function diff(o, f) {
  if (!f) return 'dropped';
  const out = [];
  for (const k of ['question', 'answer', 'wrong', 'explanation', 'source', 'sourceUrl', 'confidence', 'difficulty', 'era']) {
    const a = JSON.stringify(o[k]), b = JSON.stringify(f[k]);
    if (a === b) continue;
    if (k === 'answer' || k === 'confidence' || k === 'difficulty' || k === 'era') out.push(`${k}: “${short(o[k], 40)}” → “${short(f[k], 40)}”`);
    else if (k === 'wrong') out.push(`wrong: ${o.wrong.filter((w) => !f.wrong.includes(w)).map((w) => `“${short(w, 30)}”`).join(', ')} → ${f.wrong.filter((w) => !o.wrong.includes(w)).map((w) => `“${short(w, 30)}”`).join(', ')}`);
    else if (k === 'source') out.push(`source → ${short(f.source, 60)}`);
    else if (k === 'sourceUrl') continue;
    else out.push(k);
  }
  return out.join('; ') || 'no field change';
}

let changed = 0, kept = 0, dropped = 0;
const rows = [];
const keepRows = [];
for (const o of orig) {
  const f = final.get(o.id); const a = first.get(o.id); const b = second.get(o.id);
  const d = diff(o, f);
  const methods = [a && cell(a.method), b && `2nd pass (${b.file}): ${b.verdict}`].filter(Boolean).join(' · ');
  if (!f) dropped++;
  if (d === 'no field change') { kept++; keepRows.push(`| ${o.id} | ${short(a && a.method, 60)} | ${b ? b.verdict : '—'} |`); continue; }
  if (f) changed++;
  const notes = [a && a.note && `1st: ${a.note}`, b && b.verdict !== 'ok' && b.issue && `2nd: ${b.issue}`].filter(Boolean).map(cell).join(' — ');
  rows.push(`| ${o.id}${FLAGGED.includes(o.id) ? ' ⚑' : ''} | ${cell(d)} | ${short(methods, 120)} | ${notes} |`);
}

const flaggedRows = FLAGGED.map((id) => {
  const o = orig.find((q) => q.id === id); const f = final.get(id); const a = first.get(id); const b = second.get(id);
  return `| ${id} | ${short(o.question, 60)} | ${f ? `kept (${f.confidence})` : 'dropped'} | ${cell(f ? f.source : '')} | ${cell(a && a.note)}${b && b.verdict !== 'ok' ? ' — 2nd pass: ' + cell(b.issue) : ''} |`;
});

const conf = [...final.values()].reduce((m, q) => ((m[q.confidence] = (m[q.confidence] || 0) + 1), m), {});
const origConf = orig.reduce((m, q) => ((m[q.confidence] = (m[q.confidence] || 0) + 1), m), {});
const v2 = [...second.values()].reduce((m, r) => ((m[r.verdict] = (m[r.verdict] || 0) + 1), m), {});
const v1 = [...first.values()].reduce((m, r) => ((m[r.action] = (m[r.action] || 0) + 1), m), {});

const md = `# Question-bank audit — Valley of Vapors Trivia Trail

Generated by \`tools/write-audit-log.mjs\` from the records in \`research/audit-records/\`. The game uses
\`data/questions.json\`, built from the untouched \`research/trivia-bank.json\` by \`tools/apply-audit.mjs\`
(re-runnable: \`node games/trivia/tools/apply-audit.mjs games/trivia/research/audit-records --write\`).
For the full text of any change, diff \`data/questions.json\` against \`research/trivia-bank.json\`.

## Summary

| | Count |
|---|---|
| Questions in the research bank | ${orig.length} |
| Questions in the audited bank | ${final.size} |
| Dropped | ${dropped} |
| Changed (any field) | ${changed} |
| Unchanged after both passes | ${kept} |
| Confidence before | ${Object.entries(origConf).map(([k, v]) => `${k} ${v}`).join(', ')} |
| Confidence after | ${Object.entries(conf).map(([k, v]) => `${k} ${v}`).join(', ')} |
| "via search" sources remaining | ${[...final.values()].filter((q) => /via search/i.test(q.source)).length} |

## Method

1. **Copy.** \`research/trivia-bank.json\` was copied to \`data/questions.json\`; \`research/\` was not edited.
2. **First pass (every question).** The bank was split by \`sourceUrl\` into six batches (so each source
   page is fetched once per batch) and audited by six parallel research agents following
   \`audit-records/INSTRUCTIONS.md\`: fetch the cited page; confirm the answer; check that no distractor is
   arguably true; cut every explanation detail the page does not state; reword 2025–26 events the source
   only previews ("announced", "scheduled"); attribute promotional claims in the question and set the
   \`claim\` flag; re-verify or drop the ten flagged ids; replace blocked sources (HMdb, PressReader,
   Baseball-Reference, rate-limited sites) with a page that was actually read, updating \`source\`/\`sourceUrl\`.
   Result: ${Object.entries(v1).map(([k, v]) => `${k} ${v}`).join(', ')} (batch-9 holds coordinator overrides).
3. **Coordinator review.** The coordinator re-fetched the items the auditors flagged as weak (hs-0276
   Wolf Stadium caption, hs-0292 NPS tower page, hs-0308 EoA GI Revolt, hs-0329 baptism) and fixed or dropped
   them (\`batch-9.result.json\`). hs-0329 was dropped: the baptism location is only on a fan site.
4. **Second-pass sample.** An independent agent re-checked a random 40-question sample of the merged
   bank: 36 ok, 4 needed fixes (≈10%, almost all explanation add-ons).
5. **Second pass (the other ${orig.length - 41}).** Because of that rate, four more agents re-verified every
   remaining question against its source with \`audit-records/VERIFY.md\`, focusing on explanation fidelity
   and distractor overlap. Second-pass verdicts over all ${second.size} checked: ${Object.entries(v2).map(([k, v]) => `${k} ${v}`).join(', ')}.
   Fixes were folded in on top of the first pass.
6. **Screenshot review.** One more fix (hs-0230) came from reading a question in the game: its
   explanation listed other title years, so the question became "which of these years". In review,
   hs-0266's explanation ("Ruth has his own marker") was found not to support the answer "Nine"; it now
   quotes the trail page ("trained here nine times"), re-fetched 2026-10-28.
7. **Validation.** \`apply-audit.mjs\` checks every record: three distractors, no distractor equal to the
   answer, no duplicates, valid confidence/difficulty/era, explanation ≤ 220 chars, http(s) source URL.
   The test \`perf.test.mjs › bank is the audited copy\` re-checks this inside the built game.

**Verification method codes** (the \`method\` column): \`fetched sourceUrl\` — the cited page was read;
\`fetched alternative: <url>\` — the cited page was blocked or did not state the fact, so another page was
read and became the new source; \`coordinator review\` — fixed during review; the 2nd-pass column gives the
verify batch and verdict (\`ok\` = confirmed again on the page, \`fix\` = corrected).

**Residual risk.** Agents read pages through a summarizing fetch tool, asking for exact quotes; a
handful of facts rest on one source. Conflicting values from the corpus (Oaklawn 1904/1905, gambling's end,
spring counts) are either avoided, attributed to a named source, or asked as "sources disagree" items.

## The ten flagged ids

| id | Question (original) | Outcome | Source now | Notes |
|---|---|---|---|---|
${flaggedRows.join('\n')}

## Every change (${rows.length} questions; ⚑ = flagged id)

| id | What changed | Verification | Notes |
|---|---|---|---|
${rows.join('\n')}

## Unchanged questions (${keepRows.length})

Each was confirmed against its source in the first pass and, unless marked "—", again in the second.

| id | First-pass method | 2nd pass |
|---|---|---|
${keepRows.join('\n')}
`;
fs.writeFileSync(path.resolve(here, '../research/question-audit.md'), md);
console.log(`question-audit.md: ${rows.length} changed/dropped rows, ${keepRows.length} unchanged, ${dropped} dropped`);
