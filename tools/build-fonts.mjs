#!/usr/bin/env node
// Inlines the vendored OFL fonts (vendor/fonts/*.woff2, from npm @fontsource) into src/styles/fonts.css as data URIs.
// Chrome blocks @font-face loads from file:// pages, and shared/tools/inline.mjs inlines @import but not url(), so the
// fonts travel inside the stylesheet. The board illustrator (tools/map/illustrate.mjs) loads the same file.
//   node tools/build-fonts.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const GAME = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(GAME, 'vendor', 'fonts');
const FACES = [
  // hand-printed map lettering: street names, hillside names, plate sub-lines
  ['Kalam', 400, 'normal', 'kalam-latin-400-normal.woff2'],
  ['Kalam', 700, 'normal', 'kalam-latin-700-normal.woff2'],
  // vintage wood-type display: the title scroll and the district scroll plates
  ['Rye', 400, 'normal', 'rye-latin-400-normal.woff2'],
];
let css = '/* Generated by tools/build-fonts.mjs from vendor/fonts (SIL Open Font License 1.1). Do not edit. */\n';
for (const [family, weight, style, file] of FACES) {
  const b64 = fs.readFileSync(path.join(SRC, file)).toString('base64');
  css += `@font-face{font-family:"${family}";font-style:${style};font-weight:${weight};font-display:block;` +
    `src:url(data:font/woff2;base64,${b64}) format("woff2")}\n`;
}
fs.writeFileSync(path.join(GAME, 'src', 'styles', 'fonts.css'), css);
console.log('src/styles/fonts.css', (css.length / 1024).toFixed(1), 'KB');
